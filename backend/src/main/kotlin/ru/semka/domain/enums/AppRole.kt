package ru.semka.domain.enums

/**
 * роли пользователя на уровне всего приложения (таблица users.role).
 * не путать с MemberRole — это роль внутри конкретного кошелька.
 */
enum class AppRole {
    USER, // обычный пользователь — кошельки, операции, отчёты
    ADMIN, // администратор — доступ к /actuator (мониторинг), в демо почти не используется
}
